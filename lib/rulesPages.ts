function sizeLabel(size: string): string {
  const amount = Number(size)
  return Number.isFinite(amount) && amount >= 1000 ? `${amount / 1000}K` : size
}

export function formatRuleValue(value: RuleValue, key: RuleRow['key'], lang: RulesLang): string {
  const ru = lang === 'ru'
  switch (value.kind) {
    case 'none':
      return ru ? 'не подтверждено' : 'not confirmed'
    case 'pct':
      return `${value.value}%`
    case 'usd':
      return Object.entries(value.value)
        .sort((a, b) => Number(a[0]) - Number(b[0]))
        .map(([size, amount]) => `$${amount.toLocaleString('en-US')} (${sizeLabel(size)})`)
        .join(' / ')
    case 'availability':
      if (value.value === true) return ru ? 'разрешено' : 'Allowed'
      if (value.value === false) return ru ? 'запрещено' : 'Not allowed'
      if (value.value === 'restricted') return ru ? 'с ограничениями' : 'Allowed with conditions'
      return ru ? 'не подтверждено' : 'not confirmed'
    case 'list':
      return ru ? ruPlatformList(value.value) : value.value.join(', ')
    case 'text':
      if (key === 'drawdownType' && DRAWDOWN_LABEL[value.value]) return DRAWDOWN_LABEL[value.value][lang]
      if (key === 'payoutFrequency' && PAYOUT_LABEL[value.value]) return PAYOUT_LABEL[value.value][lang]
      return value.value
  }
}

/** A row's headline value: the firm-wide value when uniform, else a "varies" marker. */
export function headlineValue(row: RuleRow, lang: RulesLang): string {
  const ru = lang === 'ru'
  if (row.summary === null) return ru ? 'не подтверждено' : 'Not confirmed'
  const values = row.byProduct?.map(item => JSON.stringify(item.value)) ?? []
  const uniform = row.byProduct && row.byProduct.length > 0 && new Set(values).size === 1 && row.byProduct[0].value.kind !== 'none'
  if (uniform && row.byProduct) return formatRuleValue(row.byProduct[0].value, row.key, lang)
  if (/^none\b/i.test(row.summary)) return ru ? 'нет' : 'None'
  if (row.byProduct && row.byProduct.some(item => item.value.kind !== 'none')) return ru ? 'зависит от продукта' : 'Varies by product'
  // Free-text summary from the firm's own wording (English); RU never names hidden exchanges.
  if (ru && row.key === 'platforms') return ruPlatformList(row.summary.split(/\s*,\s*/).filter(Boolean))
  return ru ? ruRedactExchanges(row.summary) : row.summary
}
