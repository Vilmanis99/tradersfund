/** Wording that marks a field as not (fully) confirmed by the firm. */
const UNCONFIRMED = /not stated|not re-confirmed|unverified|unknown|unclear|not confirmed|conflict|contradict/i
const CONTRADICTION = /contradict|conflict/i

export type FieldIssue = 'missing' | 'unconfirmed' | 'contradiction' | 'unsourced' | 'stale' | 'review-hold'

/* ── Product-level flags (strict gate, Code Reviewer 26.10.2026) ──────
 * A page is noindex when ANY product of the firm carries a conflict,
 * contradiction or unconfirmed flag, or a 'not stated' style value, for a
 * required field. The data marks these in four places, all checked:
 *   1. firms.json rules.<field>: summary / note wording, and byProduct values
 *      (null or 'not stated' style text for any product);
 *   2. challenges/<firm>.json: the product's own field is null or 'not stated'
 *      (drawdown, split, payout frequency, news, weekend; EAs in evaluateEa);
 *   3. challenges/<firm>.json notes[]: a sentence naming the field together
 *      with conflict / unresolved / unverified wording (resolved ones skipped);
 *   4. the product's capture file (_captures/<firm>-<sourceCapturedAt>.json):
 *      unresolvedConflicts[].field, sourceConflicts[].field / id, open or
 *      still-unresolved conflict entries, and fieldEvidence.<field>.conflictingQuote.
 */
const FLAG_WORDS = /conflict|contradict|unresolved|cannot both be current|not (?:yet )?(?:re-?)?(?:confirmed|verified)|\bunverified\b|do not publish|disputed/i
const RESOLVED_WORDS = /(?<!un)resolved\b|superseded/i

const FIELD_WORDS: Record<RequiredRuleKey, RegExp> = {
  drawdownType: /drawdown ?type|drawdownType/i,
  dailyLoss: /daily ?loss|dailyLoss|\bDLL\b/i,
  maxLoss: /max(?:imum)? ?(?:loss|drawdown)|maxLoss|\bMLL\b|trailing max(?:imum)? drawdown/i,
  consistency: /consisten/i,
  newsTrading: /\bnews\b/i,
  ea: /\bEAs?\b|expert advisor|algorithmic|automated trading|\bbots?\b/i,
  weekendHolding: /weekend/i,
  profitSplit: /profit ?split|profitSplit|\bsplit\b/i,
  payoutFrequency: /payout ?frequency|payoutFrequency|(?:payout|withdrawal|reward) (?:cadence|cycle|schedule|frequency)/i,
}

/** Challenge fields whose null means "not stated" for that product. */
const PRODUCT_VALUE: Partial<Record<RequiredRuleKey, (challenge: Challenge) => unknown>> = {
  drawdownType: challenge => challenge.drawdownType,
  profitSplit: challenge => challenge.profitSplitPct,
  payoutFrequency: challenge => challenge.payoutFrequency,
  newsTrading: challenge => challenge.rules?.news ?? null,
  weekendHolding: challenge => challenge.rules?.weekend ?? null,
}

const sentences = (text: string) => text.split(/(?<=[.!?])\s+(?=[A-Z"'(])/)

function noteFlags(key: RequiredRuleKey, notes: readonly string[] | undefined): string[] {
  const hits: string[] = []
  for (const note of notes ?? []) {
    for (const sentence of sentences(note)) {
      if (FIELD_WORDS[key].test(sentence) && FLAG_WORDS.test(sentence) && !RESOLVED_WORDS.test(sentence)) hits.push(sentence.slice(0, 160))
    }
  }
  return hits
}

const captureCache = new Map<string, unknown>()
function readCapture(slug: string, date: string): unknown {
  const file = path.join(process.cwd(), 'content/data/challenges/_captures', `${slug}-${date}.json`)
  if (!captureCache.has(file)) {
    let data: unknown = null
    try { data = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null } catch { data = null }
    captureCache.set(file, data)
  }
  return captureCache.get(file)
}

/** Conflict entries in a capture file that name this field (see header, point 4). */
function captureFlags(key: RequiredRuleKey, capture: unknown, productSlug: string): string[] {
  const hits: string[] = []
  const visit = (node: unknown, trail: string[]): void => {
    if (Array.isArray(node)) { node.forEach(item => visit(item, trail)); return }
    if (!node || typeof node !== 'object') return
    const record = node as Record<string, unknown>
    for (const [name, value] of Object.entries(record)) {
      const lower = name.toLowerCase()
      const openList = /^(unresolvedconflicts|sourceconflicts|stillunresolved|openconflicts?)$/.test(lower) || (/conflict$/.test(lower) && lower !== 'resolvedconflicts')
      if (openList) {
        for (const entry of Array.isArray(value) ? value : [value]) {
          const text = typeof entry === 'string' ? entry : JSON.stringify(entry)
          const field = entry && typeof entry === 'object' ? String((entry as Record<string, unknown>).field ?? (entry as Record<string, unknown>).id ?? '') : ''
          const resolved = entry && typeof entry === 'object' && ((entry as Record<string, unknown>).resolvedAt || /^resolved/i.test(String((entry as Record<string, unknown>).resolution ?? '')))
          if (!resolved && (FIELD_WORDS[key].test(field) || (!field && FIELD_WORDS[key].test(text)))) hits.push(`${name}: ${(field || text).slice(0, 120)}`)
        }
      } else if (lower === 'fieldevidence' && value && typeof value === 'object') {
        const productMatch = !record.productSlug || record.productSlug === productSlug
        for (const [field, evidence] of Object.entries(value as Record<string, unknown>)) {
          if (productMatch && FIELD_WORDS[key].test(field) && evidence && typeof evidence === 'object' && (evidence as Record<string, unknown>).conflictingQuote) {
            hits.push(`fieldEvidence.${field}.conflictingQuote`)
          }
        }
      } else if (lower !== 'resolvedconflicts') {
        visit(value, [...trail, name])
      }
    }
  }
  visit(capture, [])
  return hits
}

export interface ProductFlag { productSlug: string; issue: 'unconfirmed' | 'contradiction'; where: string }

/** Every product-level flag for one required field (points 2-4 of the header). */
export function productFlagsFor(key: RequiredRuleKey, slug: string, challenges: Challenge[], capture = readCapture): ProductFlag[] {
  const flags: ProductFlag[] = []
  for (const challenge of challenges) {
    const read = PRODUCT_VALUE[key]
    if (read) {
      const value = read(challenge)
      if (value === null || value === undefined) flags.push({ productSlug: challenge.productSlug, issue: 'unconfirmed', where: `challenges/${slug}.json ${challenge.productSlug}: value not stated (null)` })
      else if (typeof value === 'string' && UNCONFIRMED.test(value)) flags.push({ productSlug: challenge.productSlug, issue: 'unconfirmed', where: `challenges/${slug}.json ${challenge.productSlug}: "${value}"` })
    }
    for (const hit of noteFlags(key, challenge.notes)) {
      flags.push({ productSlug: challenge.productSlug, issue: 'contradiction', where: `challenges/${slug}.json ${challenge.productSlug} note: ${hit}` })
    }
    for (const hit of captureFlags(key, capture(slug, challenge.sourceCapturedAt), challenge.productSlug)) {
      flags.push({ productSlug: challenge.productSlug, issue: 'contradiction', where: `_captures/${slug}-${challenge.sourceCapturedAt}.json: ${hit}` })
    }
  }
  return flags
}

