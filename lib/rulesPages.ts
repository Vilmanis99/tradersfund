/**
 * `verdicts` overrides the on-disk verdict lookup; tests use it to pass an
 * in-memory fixture instead of writing to content/.
 */
export interface RulesModelOptions {
  verdicts?: { en?: Verdict | null; ru?: Verdict | null }
  /** Test-only overrides; production reads challenges, captures and holds from disk / this module. */
  challenges?: Challenge[]
  readCapture?: (slug: string, date: string) => unknown
  holds?: typeof RULES_REVIEW_HOLDS
}

export function buildRulesPageModel(firm: Firm, now = new Date(), options: RulesModelOptions = {}): RulesPageModel | null {
  const rules = firm.rules
  if (!rules) return null
  const slug = firmSlug(firm.name)
  const challenges = options.challenges ?? getChallengesByFirm(slug)
  const productNames = new Map(challenges.map(challenge => [challenge.productSlug, challenge.productName]))

  const daily = lossField(rules, 'daily')
  const max = lossField(rules, 'max')
  const definitions: Array<{ key: RequiredRuleKey | 'platforms'; dataField: string; field: FirmRuleField<unknown> | null | 'ea' }> = [
    { key: 'drawdownType', dataField: 'rules.drawdownType', field: rules.drawdownType as FirmRuleField<unknown> },
    { key: 'dailyLoss', dataField: daily.dataField, field: daily.field },
    { key: 'maxLoss', dataField: max.dataField, field: max.field },
    { key: 'consistency', dataField: 'rules.consistencyPct', field: rules.consistencyPct as FirmRuleField<unknown> },
    { key: 'newsTrading', dataField: 'rules.newsTrading', field: rules.newsTrading as FirmRuleField<unknown> },
    { key: 'ea', dataField: 'challenges[].rules.ea', field: 'ea' },
    { key: 'weekendHolding', dataField: 'rules.weekendHolding', field: rules.weekendHolding as FirmRuleField<unknown> },
    { key: 'profitSplit', dataField: 'rules.profitSplitPct', field: rules.profitSplitPct as FirmRuleField<unknown> },
    { key: 'payoutFrequency', dataField: 'rules.payoutFrequency', field: rules.payoutFrequency as FirmRuleField<unknown> },
    { key: 'platforms', dataField: 'rules.platforms', field: (rules.platforms ?? null) as FirmRuleField<unknown> | null },
  ]
  const rows: RuleRow[] = definitions.map(def => {
    const row: RuleRow = {
      key: def.key,
      required: def.key !== 'platforms',
      dataField: def.dataField,
      productFlags: [],
      ...(def.field === 'ea' ? evaluateEa(slug, challenges, now) : evaluateField(def.field, productNames, now)),
    }
    if (def.key === 'platforms') return row
    const key = def.key as RequiredRuleKey
    const issues = new Set(row.issues)
    // 1. firms.json byProduct: any product without a stated value, or with 'not stated' wording.
    for (const item of row.byProduct ?? []) {
      const value = item.value
      const noneByRule = row.summary !== null && /^none\b/i.test(row.summary)
      if ((value.kind === 'none' && !noneByRule) || (value.kind === 'text' && UNCONFIRMED.test(value.value))) {
        issues.add('unconfirmed')
        row.productFlags.push({ productSlug: item.productSlug, issue: 'unconfirmed', where: `firms.json ${def.dataField}.byProduct.${item.productSlug}: not stated` })
      }
    }
    // 2-4. Challenge values, notes and capture files.
    for (const flag of productFlagsFor(key, slug, challenges, options.readCapture)) {
      issues.add(flag.issue)
      row.productFlags.push(flag)
    }
    for (const hold of options.holds ?? RULES_REVIEW_HOLDS) {
      if (hold.slug === slug && hold.key === key && row.summary === hold.whileSummary) {
        issues.add('review-hold')
        row.productFlags.push({ productSlug: '*', issue: 'contradiction', where: `review hold: ${hold.reason}` })
      }
    }
    row.issues = [...issues]
    return row
  })

  const products: ProductRow[] = challenges.map(challenge => ({
    productSlug: challenge.productSlug,
    productName: challenge.productName,
    phases: challenge.phases,
    profitTargets: challenge.profitTargets,
    minTradingDays: challenge.minTradingDays,
    dailyLossPct: challenge.dailyLossPct,
    maxLossPct: challenge.maxLossPct,
    drawdownType: challenge.drawdownType,
    profitSplitPct: challenge.profitSplitPct,
    profitSplitTiers: (challenge.profitSplitTiers ?? []).map(tier => ({ traderPct: tier.traderPct, appliesTo: tier.appliesTo })),
    sourceUrl: challenge.sourceUrl,
    sourceCapturedAt: challenge.sourceCapturedAt,
    fresh: isChallengeFresh(challenge, now, RULES_MAX_AGE_DAYS),
  }))

  const sourceMap = new Map<string, { url: string; capturedAt: string; fields: Set<string> }>()
  for (const row of rows) {
    for (const item of row.evidence) {
      if (!/^https:\/\//.test(item.sourceUrl)) continue
      const current = sourceMap.get(item.sourceUrl)
      if (current) {
        current.fields.add(row.key)
        if (item.capturedAt > current.capturedAt) current.capturedAt = item.capturedAt
      } else {
        sourceMap.set(item.sourceUrl, { url: item.sourceUrl, capturedAt: item.capturedAt, fields: new Set([row.key]) })
      }
    }
  }
  const sources = [...sourceMap.values()]
    .map(source => ({ url: source.url, capturedAt: source.capturedAt, fields: [...source.fields] }))
    .sort((a, b) => a.url.localeCompare(b.url))

  const required = rows.filter(row => row.required)
  const allDates = [rules.capturedAt, ...required.flatMap(row => row.evidence.map(item => item.capturedAt))]
  const oldestCapture = oldest(allDates)
  const newestCapture = newest(allDates)
  const gaps = required
    .filter(row => row.issues.length > 0)
    .map(row => ({ key: row.key as RequiredRuleKey, issues: row.issues }))

  const firmIssues: string[] = []
  if (!isCaptureFresh(rules.capturedAt, now)) firmIssues.push(`rules block captured ${rules.capturedAt}, older than ${RULES_MAX_AGE_DAYS} days`)
  if (products.length === 0) firmIssues.push('no challenge products on file')
  if (isSourceHoldFirm(slug)) firmIssues.push('firm is on source hold')
  const dataEligible = gaps.length === 0 && firmIssues.length === 0

  const dataReasons = [
    ...firmIssues,
    ...gaps.map(gap => `${RULE_LABELS[gap.key].en}: ${describeIssues(gap.issues)}`),
  ]

  const overrides = options.verdicts ?? {}
  const enVerdict = 'en' in overrides ? overrides.en ?? null : loadVerdict('rules', slug, 'en')
  const ruVerdict = 'ru' in overrides ? overrides.ru ?? null : loadVerdict('rules', slug, 'ru')

  const enReasons = [...dataReasons]
  if (RULES_REQUIRE_VERDICT.en && !enVerdict) enReasons.push('no EN verdict file')

  let ru: RulesPageModel['ru'] = null
  const template = (RU_RULES_TEMPLATE_SLUGS as readonly string[]).includes(slug)
  if (template || Object.hasOwn(RU_RULES_HANDWRITTEN, slug)) {
    const ruPath = ruRulesPath(slug)
    const ruReasons = [...dataReasons]
    // Template twins and hand-written pages pass the same gate (Code Reviewer 27.10.2026): complete,
    // unflagged data plus a RU writer verdict. A hand-written page reads ru.indexable for its robots
    // and hreflang, so it flips to indexable on its own once the flags clear.
    if (RULES_REQUIRE_VERDICT.ru && !ruVerdict) ruReasons.push('no RU verdict file')
    // RU pages go live through the RU registry (sitemap, inlinks, RU audits).
    if (!isRussianRoutePath(ruPath)) ruReasons.push(template ? 'not registered in RUSSIAN_ROUTE_EDITORIAL_DATES' : 'hand-written RU page not published yet')
    ru = { path: ruPath, template, indexable: ruReasons.length === 0, reasons: ruReasons }
  }

  return {
    slug,
    firm,
    rules,
    rows,
    products,
    sources,
    oldestCapture,
    newestCapture,
    gaps,
    dataEligible,
    enVerdict,
    ruVerdict,
    en: { path: enRulesPath(slug), indexable: enReasons.length === 0, reasons: enReasons },
    ru,
  }
}

let cache: { day: string; models: RulesPageModel[] } | null = null

/** All firms with a rules block. Cached per UTC day (freshness is day-granular). */
export function getRulesPageModels(now = new Date()): RulesPageModel[] {
  const day = now.toISOString().slice(0, 10)
  if (cache && cache.day === day) return cache.models
  const models = getAllFirms()
    .map(firm => buildRulesPageModel(firm, now))
    .filter((model): model is RulesPageModel => model !== null)
  cache = { day, models }
  return models
}

export function getRulesPageModel(slug: string, now = new Date()): RulesPageModel | null {
  return getRulesPageModels(now).find(model => model.slug === slug) ?? null
}

/**
 * Hand-written RU rules pages (RU_RULES_HANDWRITTEN) that the gate keeps noindex. They stay
 * registered RU routes (200, inlinks, editorial date) but are left out of the sitemap, IndexNow
 * and hreflang, and the release crawl checks them as noindex pages instead of acquisition pages.
 */
export function gatedRuRulesHandwrittenPaths(now = new Date()): string[] {
  return getRulesPageModels(now)
    .filter(model => model.ru && !model.ru.template && !model.ru.indexable)
    .map(model => model.ru!.path)
}

/** Indexable EN rules paths (sitemap source). */
export function indexableEnRulesPaths(now = new Date()): string[] {
  return getRulesPageModels(now).filter(model => model.en.indexable).map(model => model.en.path)
}

/** EN rules href for internal links, only when that page is indexable. */
export function indexableRulesHref(slug: string, now = new Date()): string | null {
  const model = getRulesPageModel(slug, now)
  return model?.en.indexable ? model.en.path : null
}

/** RU rules href for internal RU links, only when that page is indexable (and therefore registered). */
export function indexableRuRulesHref(slug: string, now = new Date()): string | null {
  const model = getRulesPageModel(slug, now)
  return model?.ru?.indexable ? model.ru.path : null
}

/**
 * EN↔RU hreflang pair for a rules path, only when BOTH sides are indexable.
 * A hand-written RU rules page (RU_RULES_HANDWRITTEN) should call this from
 * its own metadata so the pair is reciprocal.
 */
export function rulesRoutePair(pathname: string, now = new Date()): { en: string; ru: string } | undefined {
  const model = getRulesPageModels(now).find(item => item.en.path === pathname || item.ru?.path === pathname)
  if (!model || !model.ru || !model.en.indexable || !model.ru.indexable) return undefined
  return { en: model.en.path, ru: model.ru.path }
}

export function rulesLanguageAlternates(pathname: string, now = new Date()) {
  const pair = rulesRoutePair(pathname, now)
  return pair ? { en: pair.en, ru: pair.ru, 'x-default': pair.en } : undefined
}

