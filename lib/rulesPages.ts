/* ── Helpers ───────────────────────────────────────────────────────── */

export function isCaptureFresh(iso: string | null, now = new Date(), maxAgeDays = RULES_MAX_AGE_DAYS): boolean {
  if (!iso) return false
  return isChallengeFresh({ sourceCapturedAt: iso }, now, maxAgeDays)
}

function oldest(dates: Array<string | null | undefined>): string | null {
  const valid = dates.filter((date): date is string => typeof date === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(date))
  return valid.length ? valid.sort()[0] : null
}

function newest(dates: Array<string | null | undefined>): string | null {
  const valid = dates.filter((date): date is string => typeof date === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(date))
  return valid.length ? valid.sort()[valid.length - 1] : null
}

function captureExists(slug: string, date: string): boolean {
  return fs.existsSync(path.join(process.cwd(), 'content/data/challenges/_captures', `${slug}-${date}.json`))
}

function toValue(raw: unknown): RuleValue {
  if (raw === null || raw === undefined) return { kind: 'none' }
  if (typeof raw === 'number') return { kind: 'pct', value: raw }
  if (typeof raw === 'boolean' || raw === 'restricted') return { kind: 'availability', value: raw as RuleAvailability }
  if (Array.isArray(raw)) return { kind: 'list', value: raw.map(String) }
  if (typeof raw === 'object') return { kind: 'usd', value: raw as UsdBySize }
  return { kind: 'text', value: String(raw) }
}

function evaluateField(
  field: FirmRuleField<unknown> | null | undefined,
  products: Map<string, string>,
  now: Date,
): Omit<RuleRow, 'key' | 'required' | 'dataField' | 'productFlags'> {
  const evidence: FieldEvidence[] = (field?.evidence ?? []).map(item => ({
    sourceUrl: item.sourceUrl,
    quote: item.quote,
    quoteKind: item.quoteKind,
    capturedAt: item.capturedAt,
    productSlug: item.productSlug,
  }))
  const issues: FieldIssue[] = []
  const summary = field?.summary ?? null
  if (!field || summary === null) {
    issues.push('missing')
  } else {
    if (UNCONFIRMED.test(summary)) issues.push('unconfirmed')
    if (field.note && CONTRADICTION.test(field.note)) issues.push('contradiction')
  }
  const verbatim = evidence.filter(item => item.quoteKind === 'verbatim' && /^https:\/\//.test(item.sourceUrl) && item.quote?.trim())
  if (summary !== null && verbatim.length === 0) issues.push('unsourced')
  const oldestCapture = oldest(evidence.map(item => item.capturedAt))
  if (summary !== null && evidence.length > 0 && !evidence.every(item => isCaptureFresh(item.capturedAt, now))) issues.push('stale')
  const byProduct = field?.byProduct
    ? Object.entries(field.byProduct).map(([productSlug, value]) => ({
      productSlug,
      productName: products.get(productSlug) ?? productSlug,
      value: toValue(value),
    }))
    : null
  return { summary, byProduct, note: field?.note ?? null, evidence, issues, oldestCapture }
}

/** EAs are not in the firms.json rules block; they come from each product's challenge rules.ea. */
function evaluateEa(slug: string, challenges: Challenge[], now: Date): Omit<RuleRow, 'key' | 'required' | 'dataField' | 'productFlags'> {
  const issues: FieldIssue[] = []
  if (challenges.length === 0) issues.push('missing')
  const values = challenges.map(challenge => challenge.rules?.ea ?? null)
  if (values.some(value => value === null)) issues.push(values.every(value => value === null) ? 'missing' : 'unconfirmed')
  const unsourced = challenges.some(challenge => !/^https:\/\//.test(challenge.sourceUrl) || !captureExists(slug, challenge.sourceCapturedAt))
  if (challenges.length && unsourced) issues.push('unsourced')
  if (challenges.length && !challenges.every(challenge => isChallengeFresh(challenge, now, RULES_MAX_AGE_DAYS))) issues.push('stale')
  const uniform = values.length > 0 && values.every(value => value === values[0]) ? values[0] : undefined
  const summary = challenges.length === 0
    ? null
    : uniform !== undefined && uniform !== null
      ? uniform === true ? 'allowed' : uniform === false ? 'not allowed' : 'restricted'
      : values.every(value => value === null) ? null : 'product-specific'
  return {
    summary,
    byProduct: challenges.map(challenge => ({
      productSlug: challenge.productSlug,
      productName: challenge.productName,
      value: toValue(challenge.rules?.ea ?? null),
    })),
    note: null,
    evidence: challenges.map(challenge => ({
      sourceUrl: challenge.sourceUrl,
      quote: null,
      quoteKind: 'product-capture' as const,
      capturedAt: challenge.sourceCapturedAt,
      productSlug: challenge.productSlug,
    })),
    issues: [...new Set(issues)],
    oldestCapture: oldest(challenges.map(challenge => challenge.sourceCapturedAt)),
  }
}

function lossField(rules: FirmRules, kind: 'daily' | 'max'): { field: FirmRuleField<unknown> | null; dataField: string } {
  const pctKey = kind === 'daily' ? 'dailyLossPct' : 'maxLossPct'
  const usdKey = kind === 'daily' ? 'dailyLossUsd' : 'maxLossUsd'
  if (rules.lossLimitUnit === 'usd') return { field: rules[usdKey] as FirmRuleField<unknown>, dataField: `rules.${usdKey}` }
  if (rules.lossLimitUnit === 'pct') return { field: rules[pctKey] as FirmRuleField<unknown>, dataField: `rules.${pctKey}` }
  // 'mixed' or null: use whichever unit is published; null when neither is.
  if (rules[pctKey]?.summary != null) return { field: rules[pctKey] as FirmRuleField<unknown>, dataField: `rules.${pctKey}` }
  if (rules[usdKey]?.summary != null) return { field: rules[usdKey] as FirmRuleField<unknown>, dataField: `rules.${usdKey}` }
  return { field: null, dataField: `rules.${pctKey} | rules.${usdKey}` }
}

const ISSUE_TEXT: Record<FieldIssue, string> = {
  missing: 'not published in our data',
  unconfirmed: 'not confirmed for every product',
  contradiction: 'official sources contradict each other',
  unsourced: 'no verbatim first-party quote',
  stale: `evidence older than ${RULES_MAX_AGE_DAYS} days`,
  'review-hold': 'held for a data fix after review',
}

export function describeIssues(issues: FieldIssue[]): string {
  return issues.map(issue => ISSUE_TEXT[issue]).join('; ')
}

