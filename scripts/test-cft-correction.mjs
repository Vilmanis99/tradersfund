/** Corrective capture and review invariants; no network or source-date mutation. */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { getChallengesByFirm, getAllFirms, isChallengeFresh, computeTrueCost, minimumCostToFundedUsd } from '../lib/firms.ts'

const products = getChallengesByFirm('crypto-fund-trader')
const bySlug = Object.fromEntries(products.map(product => [product.productSlug, product]))
assert.equal(products.length, 5, 'Retain unresolved programmes instead of deleting them')
// 2026-10-19 recapture re-verified all five products; the 2026-10-20 article-slot recapture (crypto-fund-trader-2026-10-20.json, articleSlotRecapture) re-verified Evaluation, Accelerated and Instant (Break and Ascend stay under the source-conflict watch).
const date = new Date('2026-10-20T12:00:00Z')
const freshAtCorrection = products.filter(product => isChallengeFresh(product, date))
assert.deepEqual(freshAtCorrection.map(product => product.productSlug), ['evaluation', 'ascend', 'accelerated', 'instant', 'break'])
assert.equal(freshAtCorrection.reduce((total, product) => total + product.accountSizes.filter(tier => tier.priceUsd > 0).length, 0), 18)
assert.equal(products.reduce((total, product) => total + product.accountSizes.filter(tier => tier.priceUsd > 0).length, 0), 18, 'Ascend is not purchasable (store API 2026-10-20), so its six terms fees are not priced tiers')
for (const slug of ['evaluation', 'accelerated', 'instant']) {
  const product = bySlug[slug]
  assert.equal(product.sourceCapturedAt, '2026-10-20')
  assert.equal(product.payoutFirstDays, null, 'Conditional trading/calendar/profit thresholds are not unconditional calendar-day payouts')
  assert.equal(product.payoutFrequency, null)
  assert.equal(product.minTradingDays, 0)
  assert.equal(product.maxTradingDaysUnlimited, true)
  assert.equal(isChallengeFresh(product, new Date('2026-11-20T00:00:00Z')), false)
}
assert.equal(bySlug.instant.profitSplitPct, 50)
assert.equal(bySlug.instant.drawdownType, null, 'Do not invent the Instant floor basis')
assert.equal(bySlug.ascend.profitSplitPct, null, 'Fixed award cannot become an 80% continuing account')
assert.equal(bySlug.break.sourceCapturedAt, '2026-10-19', 'Unresolved price-conflict watch: do not renew Break verification')
assert.ok(['2026-10-19', '2026-10-20'].includes(bySlug.ascend.sourceCapturedAt), 'Ascend availability recheck date')
assert.equal(bySlug.break.consistencyScope, 'funded', 'Break page: 40% applies on a BREAK funded account')
assert.deepEqual(bySlug.ascend.accountSizes.map(tier => tier.priceUsd), [null, null, null, null, null, null], 'Not purchasable on 2026-10-20; terms ladder kept in notes')
assert.deepEqual(bySlug.break.accountSizes.map(tier => tier.priceUsd), [70, 140, 200])
assert.deepEqual(bySlug.ascend.accountSizes.map(tier => minimumCostToFundedUsd(bySlug.ascend, tier)), [null, null, null, null, null, null])
assert.deepEqual(bySlug.break.accountSizes.map(tier => minimumCostToFundedUsd(bySlug.break, tier)), [208, 338, 528])
assert.deepEqual(bySlug.break.accountSizes.map(tier => tier.activationFeeUsd), [138, 198, 328])
const instantTier = bySlug.instant.accountSizes.find(tier => tier.sizeUsd === 10000)
assert.equal(computeTrueCost({ ...bySlug.instant, ...instantTier }).breakEvenProfit, 950)
const firm = getAllFirms().find(firm => firm.name === 'Crypto Fund Trader')
for (const field of ['profitSplitPct', 'payoutFrequency', 'drawdownType']) assert.equal(firm[field], null, `No misleading blanket ${field} card claim`)
assert.equal(firm.lastUpdated, '2026-10-20', '2026-10-20 article-slot recapture refreshed firm metadata')
assert.equal(firm.maxAllocation, '$300,000', 'FAQ per-user funded allocation cap')
assert.equal(firm.trustpilotCount, null, 'Suppressed Trustpilot profile keeps count null')

const generated = spawnSync(process.execPath, ['scripts/gen-truecost.mjs', 'crypto-fund-trader'], { encoding: 'utf8' })
assert.equal(generated.status, 0, generated.stderr)
const tables = generated.stdout.replaceAll('\r\n', '\n').match(/<!-- [^\n]*generated by scripts\/gen-truecost\.mjs -->[\s\S]*?<\/table>/g)
assert.equal(tables?.length, 4, 'Only the four applicable percentage-share cost tables are generated')
const review = readFileSync(new URL('../content/posts/crypto-fund-trader-review.md', import.meta.url), 'utf8').replaceAll('\r\n', '\n')
for (const table of tables) assert(review.includes(table), 'Review tables exactly match the generator using computeTrueCost')
assert.equal((review.match(/generated by scripts\/gen-truecost\.mjs/g) ?? []).length, 4)
assert(review.includes('author: "Edris Derakhshi"'))
assert(review.includes("Ascend has no percentage-split True-Cost table"))
assert(review.includes('Break Challenge true-cost projection'))
