/** First-party Topstep correction, propagated prose and generated cost invariants. */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { getChallengesByFirm, getAllFirms, isChallengeFresh, challengeTierEconomics } from '../lib/firms.ts'
import { validateWatchCaptureProvenance } from '../lib/challengeWatchEvidence.ts'

const read = file => readFileSync(new URL(`../${file}`, import.meta.url), 'utf8').replaceAll('\r\n', '\n')
const json = file => JSON.parse(read(file))
const products = getChallengesByFirm('topstep')
assert.equal(products.length, 2)
assert.deepEqual(products.map(product => product.accountSizes.map(tier => tier.priceUsd)), [[49, 99, 199], [95, 149, 229]])
assert.deepEqual(products.map(product => product.activationFeeUsd), [149, 0])
for (const product of products) {
  assert.equal(product.sourceCapturedAt, '2026-09-08')
  assert.equal(product.pricingModel, 'monthly-subscription')
  assert.equal(product.minTradingDays, null, 'Conflicting minimum must not become verified two-day or zero-day permission')
  assert.equal(product.payoutFirstDays, null, 'Conditional trading days are not unconditional calendar days')
  assert.equal(product.maxLossPct, null, 'Dollar tier limits are not a uniform percentage')
  assert.equal(product.rules.ea, 'restricted')
  assert.equal(product.rules.copyTrading, 'restricted')
  assert.deepEqual(product.accountSizes.map(tier => tier.maxLossUsd), [2000, 3000, 4500])
  assert.equal(isChallengeFresh(product, new Date('2026-10-08T12:00:00Z')), true)
  assert.equal(isChallengeFresh(product, new Date('2026-10-09T12:00:00Z')), false)
  const economics = challengeTierEconomics(product, product.accountSizes[1])
  assert.equal(economics.minimumCost, product.activationFeeUsd + product.accountSizes[1].priceUsd)
  assert.equal(economics.rMultiple, economics.breakEvenProfit / 3000)
  assert.equal(economics.dayCount, null)
}
const capture = json('content/data/challenges/_captures/topstep-2026-09-08.json')
assert.equal(capture.reviewStatus, 'ready')
assert.deepEqual(capture.releaseBlockers, [])
assert.equal(capture.unresolvedConflicts[0].field, 'minTradingDays')
for (const product of capture.products) {
  for (const tier of product.accountSizes) {
    assert(tier.evidence.price.quote.includes(`$${tier.priceUsd}/month`))
    assert(tier.evidence.maxLoss.quote.includes(tier.maxLossUsd.toLocaleString('en-US')))
  }
  for (const evidence of Object.values(product.fieldEvidence)) {
    assert(evidence.quote)
    const host = new URL(evidence.sourceUrl).hostname
    assert(host === 'www.topstep.com' || host === 'help.topstep.com')
  }
}
const firm = getAllFirms().find(firm => firm.name === 'Topstep')
assert.deepEqual(firm.platforms, ['TopstepX'])
assert.equal(firm.minTradingDays, null)
assert.equal(firm.lastUpdated, '2026-07-27', 'Narrow capture does not refresh all aggregate metadata')
assert.equal(firm.trustpilotCapturedAt, '2026-07-27')
const review = read('content/posts/topstep-review.md')
const generated = spawnSync(process.execPath, ['scripts/gen-truecost.mjs', 'topstep'], { encoding: 'utf8' })
assert.equal(generated.status, 0, generated.stderr)
const tables = generated.stdout.replaceAll('\r\n', '\n').match(/<!-- [^\n]*generated by scripts\/gen-truecost\.mjs -->[\s\S]*?<\/table>/g)
assert.equal(tables.length, 2)
for (const table of tables) assert(review.includes(table), 'Review uses exact generated computeTrueCost tables')
for (const text of ['China, Canada and UK only', 'Approval and transfer are separate', 'not guaranteed access', '1–3 business days', '5–10 business days', 'at most two reactivations', '2026-05-29']) assert(review.includes(text), text)
for (const text of ['does not publish a settlement duration', 'We record 2 because', 'NinjaTrader, Quantower, TradingView', 'any R we printed would be our arithmetic']) assert(!review.includes(text), text)
assert.equal((review.match(/<h3 class="wp-block-heading">/g) ?? []).length, 7, 'Reviews v2 FAQ count')
assert(!/href="https?:\/\/(?:www\.|help\.)?topstep\.com/.test(review), 'Firm links remain /go routed')
const downstream = [
  'content/pages/how-prop-firm-challenges-work.md',
  'content/pages/true-cost-of-prop-firm-challenges.md',
  'content/posts/is-prop-firm-trading-profitable.md',
  'content/posts/what-is-prop-firm-consistency-rule.md',
  'content/posts/what-is-a-prop-firm.md',
]
for (const file of downstream) {
  const rows = read(file).split('\n').filter(line => line.includes('data-') && line.includes('topstep:'))
  assert(rows.length)
  for (const row of rows) {
    assert(row.includes('2026-09-08'), `${file}: Topstep example date`)
    assert(!row.includes('null trading days'))
  }
}
const watches = json('content/data/challenge-watch.json').filter(entry => entry.firmSlug === 'topstep')
assert.equal(watches.length, 2)
assert.deepEqual(watches.map(entry => entry.status).sort(), ['verified', 'watch'])
for (const entry of watches) assert.deepEqual(validateWatchCaptureProvenance(entry, products, () => { throw new Error('Full capture needs no rule-only lookup') }), [])
console.log('PASS: Topstep six prices, conditional rules, tier loss math, exact review tables, five downstream guides, dated watch and preserved Trustpilot age.')
