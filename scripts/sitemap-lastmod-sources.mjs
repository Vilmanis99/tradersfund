/**
 * Source projections for the sitemap lastmod manifest (content/data/sitemap-lastmod.json).
 *
 * Each "source key" is one thing that renders into one or more sitemap URLs. A key's hash
 * covers only what that surface renders, so evidence / capture / pending edits that do not
 * change visible copy do not redate pages.
 *
 * hashVersion (HASH_VERSION below) is the projection schema. When it bumps, the generator
 * migrates: re-hash content at the previous manifest commit with the new function; if the
 * result equals the current hash, keep the stored date and only rewrite hash + version.
 */
