const LEGACY_SLUGS = { brightfunded: 'bright-funded' }
export function firmSlug(name) {
  const slug = String(name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
  return LEGACY_SLUGS[slug] ?? slug
}

function stable(value, drop = () => false) {
  return JSON.stringify(value, (key, v) => {
    if (key && (VOLATILE_KEY.test(key) || drop(key))) return undefined
    if (key === 'notes' || key === 'Notes') return undefined
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      return Object.fromEntries(Object.keys(v).sort().map(k => [k, v[k]]))
    }
    return v
  })
}

function pickFirm(firm, fields) {
  const out = {}
  for (const key of fields) {
    if (Object.prototype.hasOwnProperty.call(firm, key) && !VOLATILE_KEY.test(key)) out[key] = firm[key]
  }
  return out
}

function normalizeChallengeValue(key, value) {
  if (key === 'profitSplitTiers' && Array.isArray(value)) {
    return value.map(tier => ({
      traderPct: tier.traderPct,
      stage: tier.stage,
      appliesTo: tier.appliesTo,
      appliesToRu: tier.appliesToRu,
    }))
  }
  if (key === 'consistencyRules' && Array.isArray(value)) {
    return value.map(rule => ({
      percent: rule.percent,
      scope: rule.scope,
      appliesTo: rule.appliesTo,
    }))
  }
  return value
}

function challengeRendered(products) {
  return stable(products.map(p => {
    const out = {}
    for (const key of RENDERED_CHALLENGE_FIELDS) {
      if (!Object.prototype.hasOwnProperty.call(p, key)) continue
      if (VOLATILE_KEY.test(key)) continue
      out[key] = normalizeChallengeValue(key, p[key])
    }
    out.payoutAlt = (p.notes ?? []).some(n => typeof n === 'string' && PAYOUT_ALT.test(n))
    return out
  }))
}

function challengeCompare(products) {
  return challengeRendered(products)
}

/**
 * Challenge-watch ledger: drop recheck / impact prose that India/global cards do not show
 * as primary copy; keep id, firm, products, kind, status, title, summary, effectiveAt, urls.
 */
function challengeWatchRendered(entries) {
  const list = Array.isArray(entries) ? entries : []
  return stable(list.map(e => ({
    id: e.id,
    firmSlug: e.firmSlug,
    firmName: e.firmName,
    productSlugs: e.productSlugs,
    kind: e.kind,
    status: e.status,
    title: e.title,
    summary: e.summary,
    effectiveAt: e.effectiveAt,
    sourceUrls: e.sourceUrls,
  })))
}

/** Deals hub: code, pct, scope, status — not source URL / note chrome. */
function dealsRendered(deals) {
  const list = Array.isArray(deals) ? deals : []
  // JSON.stringify directly: verifiedOn is page-visible but matches VOLATILE_KEY in stable().
  return JSON.stringify(list.map(d => ({
    firmSlug: d.firmSlug,
    status: d.status,
    mechanism: d.mechanism,
    code: d.code,
    pct: d.pct,
    amountLabel: d.amountLabel,
    scope: d.scope,
    ctaLabel: d.ctaLabel,
    verifiedOn: d.verifiedOn,
    expiresOn: d.expiresOn,
  })))
}

/**
 * RU/EN page.tsx: import lines, related-link lists, inlink chrome and pure display wrappers
 * do not change reader-visible copy for lastmod purposes.
 */
const pageCode = text => text
  .split('\n')
  .filter(line => !/^import\s/.test(line))
  .join('\n')
  // Drop related-link / inlink widgets (visible nav chrome, not page substance).
  .replace(/<RuRelatedLinks\b[^>]*\/>/g, '')
  .replace(/<RuRelatedLinks\b[\s\S]*?<\/RuRelatedLinks>/g, '')
  .replace(/\{?\s*<RuPendingLink\b[^>]*>[\s\S]*?<\/RuPendingLink>\s*\}?/g, '')
  // Normalize lastmod wiring renames (same visible date source).
  .replace(/\brussianRouteDateModified\(/g, 'RUSSIAN_ROUTE_EDITORIAL_DATES_LOOKUP(')
  .replace(/\bRUSSIAN_ROUTE_EDITORIAL_DATES\[/g, 'RUSSIAN_ROUTE_EDITORIAL_DATES_LOOKUP[')
  .replace(/\brussianPageDate\([^)]+\)/g, 'RUSSIAN_PAGE_DATE')
  .replace(/\bformatRuDate\(([^)]+)\)/g, '$1')
  .replace(/\bruFaqPageSchema\(/g, 'faqPageSchema(')
  // HTML / JSX comments
  .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/(^|[^:])\/\/[^\n]*/g, '$1')
  .replace(/\sdata-merged-from="[^"]*"/g, '')
  .replace(/\s+/g, ' ')
  .trim()

const hash = text => crypto.createHash('sha1').update(text).digest('hex').slice(0, 16)

function listFiles(dir, test) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const full = path.posix.join(dir, entry.name)
    if (entry.isDirectory()) return entry.name.startsWith('_') ? [] : listFiles(full, test)
    return test(full) ? [full] : []
  })
}

/**
 * Tracked paths and how each one splits into source keys.
 * project(text) -> Map<key, normalizedString>
 */
export function sourceSpecs() {
  const specs = []
  specs.push({
    path: 'content/data/firms.json',
    project(text) {
      const parsed = JSON.parse(text)
      const firms = Array.isArray(parsed) ? parsed : parsed.firms
      const out = new Map()
      for (const firm of firms) {
        const slug = firmSlug(firm.name)
        out.set(`firm:en:${slug}`, stable(pickFirm(firm, RENDERED_FIRM_FIELDS_EN)))
        out.set(`firm:ru:${slug}`, stable(pickFirm(firm, RENDERED_FIRM_FIELDS_RU)))
        out.set(`firm:compare:${slug}`, stable(pickFirm(firm, RENDERED_FIRM_FIELDS_COMPARE)))
        out.set(`firm:listing:${slug}`, stable(pickFirm(firm, RENDERED_FIRM_FIELDS_LISTING)))
      }
      return out
    },
  })
  for (const file of listFiles('content/data/challenges', f => f.endsWith('.json'))) {
    const slug = path.posix.basename(file, '.json')
    if (slug.startsWith('_') || file.includes('/_')) continue
    specs.push({
      path: file,
      project(text) {
        const products = JSON.parse(text)
        const list = Array.isArray(products) ? products : []
        return new Map([
          [`challenges:full:${slug}`, challengeRendered(list)],
          [`challenges:compare:${slug}`, challengeCompare(list)],
        ])
      },
    })
  }
  specs.push({
    path: 'content/data/verdict-copy.json',
    project(text) {
      const copy = JSON.parse(text)
      const out = new Map()
      for (const section of ['reviews', 'compares']) {
        for (const [key, value] of Object.entries(copy[section] ?? {})) out.set(`copy:${section}:${key}`, stable(value))
      }
      return out
    },
  })
  const plainFiles = [
    ...listFiles('content/posts', f => f.endsWith('.md')),
    ...listFiles('content/pages', f => f.endsWith('.md')),
    ...listFiles('content/verdicts', f => f.endsWith('.md')),
    ...listFiles('app/ru', f => f.endsWith('/page.tsx')),
    ...listFiles('content/data/ru-verdicts', f => f.endsWith('.json')),
    ...SPLIT_TIER_UI_FILES.filter(f => fs.existsSync(f)),
    ...fs.readdirSync('content/data')
      .filter(f => f.endsWith('.json') && !['firms.json', 'verdict-copy.json', 'sitemap-lastmod.json'].includes(f))
      .map(f => `content/data/${f}`)
      .filter(f => !LASTMOD_IGNORED_DATA_FILES.includes(f)),
  ]
  for (const file of plainFiles) {
    specs.push({
      path: file,
      project: text => {
        if (file === 'content/data/challenge-watch.json') {
          return new Map([[`file:${file}`, challengeWatchRendered(JSON.parse(text))]])
        }
        if (file === 'content/data/deals.json') {
          return new Map([[`file:${file}`, dealsRendered(JSON.parse(text))]])
        }
        return new Map([[`file:${file}`, file.endsWith('.json') ? stable(JSON.parse(text)) : file.endsWith('.tsx') || file.endsWith('.ts') ? pageCode(text) : text]])
      },
    })
  }
  return specs
}

/** Current (working tree) hashes for every source key. */
export function currentHashes() {
  const out = new Map()
  for (const spec of sourceSpecs()) {
    for (const [key, value] of spec.project(fs.readFileSync(spec.path, 'utf8'))) out.set(key, hash(value))
  }
  return out
}

/** Composite hash for one URL from its source hashes + editorial days. */
export function urlContentHash(sourceKeys, sourceHashByKey, editorialDays = []) {
  const parts = [
    ...[...sourceKeys].sort().map(k => `${k}=${sourceHashByKey.get(k) ?? sourceHashByKey[k] ?? ''}`),
    ...[...editorialDays].filter(Boolean).sort().map(d => `ed=${d}`),
  ]
  return hash(parts.join('|'))
}

/**
 * True when every listed source key has the same content hash at tip and at baseline
 * under the current projection. New keys (in tip only) count as a change.
 */
export function urlSourcesUnchanged(sourceKeys, tipHashes, baselineHashes) {
  for (const key of sourceKeys) {
    const tip = tipHashes.get(key) ?? tipHashes[key]
    const base = baselineHashes.get(key) ?? baselineHashes[key]
    if (tip == null) continue
    if (base == null || tip !== base) return false
  }
  return true
}

