/** TS source for lib/ruRouteLastmod.generated.ts. */
export function ruRoutesModule(dates) {
  return '// Generated by scripts/gen-sitemap-lastmod.mjs from content/data/sitemap-lastmod.json. Do not edit.\n' +
    '// Per Russian route: editorial date or newest change of its page, evidence and firm data (YYYY-MM-DD).\n' +
    `export const RU_ROUTE_LASTMOD: Record<string, string> = ${JSON.stringify(dates, null, 2).replace(/"/g, "'")}\n`
}

